"""Writes shared/sb-typing-text.js from the reviewed practice text in _dev/typing/text/ (sentences.json, numbers.json, paragraphs.json).
   Usage: python3 _dev/typing/make_text.py
   Every item was written for children aged 7 to 10 and reviewed for accuracy (see ARCHITECTURE.md, Typing Drills)."""
import os, json
here = os.path.dirname(os.path.abspath(__file__))
site = os.path.dirname(os.path.dirname(here))
data = {k: json.load(open(os.path.join(here, 'text', k + '.json'))) for k in ('sentences', 'numbers', 'paragraphs')}
for k, v in data.items():
    for t in v:
        assert all(32 <= ord(c) < 127 for c in t), (k, t)
out = ('/* Study Buddy typing: practice sentences and paragraphs for children (plain ASCII).\n'
       '   Generated by _dev/typing/make_text.py from _dev/typing/text/*.json. Do not edit by hand. */\n'
       '(function (root) {\n  const SBTX = ' + json.dumps(data, indent=1) + ';\n'
       '  root.SBTX = SBTX;\n  if (typeof module === \'object\' && module.exports) module.exports = SBTX;\n'
       '})(typeof window !== \'undefined\' ? window : globalThis);\n')
open(os.path.join(site, 'shared', 'sb-typing-text.js'), 'w').write(out)
print({k: len(v) for k, v in data.items()})
