"""Writes shared/sb-typing-words.js from a reviewed word list (one word per line, most common first).
   Usage: python3 _dev/typing/make_words.py _dev/typing/words.txt
   The blocklist is kept as FNV-1a hashes (in _dev/typing/blockhash.txt) so no unkind words are written in the site.
   Every word in the list was reviewed by hand for children aged 4 to 10 (see ARCHITECTURE.md, Typing)."""
import sys, os, re, json
here = os.path.dirname(os.path.abspath(__file__))
site = os.path.dirname(os.path.dirname(here))
words, seen = [], set()
for w in open(sys.argv[1]):
    w = w.strip().lower()
    if re.fullmatch(r'[a-z]+', w) and w not in seen:
        seen.add(w); words.append(w)
block = [int(x) for x in open(os.path.join(here, 'blockhash.txt')).read().split(',') if x.strip()]
out = ('/* Study Buddy typing: the word list (most common first, reviewed for children) and the blocklist as hashes.\n'
       '   Generated by _dev/typing/make_words.py. Do not edit by hand. */\n'
       '(function (root) {\n  const SBTW = {\n    words: ' + json.dumps(' '.join(words)) + '.split(\' \'),\n'
       '    block: [' + ','.join(str(b) for b in block) + ']\n  };\n'
       '  root.SBTW = SBTW;\n  if (typeof module === \'object\' && module.exports) module.exports = SBTW;\n'
       '})(typeof window !== \'undefined\' ? window : globalThis);\n')
open(os.path.join(site, 'shared', 'sb-typing-words.js'), 'w').write(out)
print(len(words), 'words,', len(block), 'blocked hashes')
