/* Mediterranean map data for the Punic Wars module. Run:  node _dev/punic-map/geo_med.mjs  (from the study-buddy folder)
   Source: world-110m.json, Natural Earth 1:110,000,000 land outlines (public domain), as TopoJSON (via the vega-datasets collection).
   Output: modules/history/punic-wars/mapdata.js (defines const PMAP): one SVG path for the land in the window below, plus the projection
   numbers so the module can place cities and routes by longitude and latitude. The projection is plain equirectangular, with the
   east-west scale shrunk by cos(40 degrees) so shapes look right at Mediterranean latitudes. */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = dirname(fileURLToPath(import.meta.url));
const topo = JSON.parse(readFileSync(join(HERE, 'world-110m.json'), 'utf8'));
const W0 = -11, W1 = 38, S0 = 29.5, N0 = 49.5;            // the window: west, east, south, north (degrees)
const KY = 30, KX = KY * Math.cos(40 * Math.PI / 180);     // pixels per degree
const WIDTH = Math.round((W1 - W0) * KX), HEIGHT = Math.round((N0 - S0) * KY);

const { scale: [sx, sy], translate: [tx, ty] } = topo.transform;
const arcs = topo.arcs.map(a => { let x = 0, y = 0; return a.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; }); });
const arcPts = i => i >= 0 ? arcs[i] : arcs[~i].slice().reverse();
const ring = idxs => { const out = []; idxs.forEach(i => { const p = arcPts(i); out.push(...(out.length ? p.slice(1) : p)); }); return out; };
const g = topo.objects.land.type === 'GeometryCollection' ? topo.objects.land.geometries : [topo.objects.land];
const polys = [];
g.forEach(o => { if (o.type === 'Polygon') polys.push(o.arcs.map(ring)); else if (o.type === 'MultiPolygon') o.arcs.forEach(p => polys.push(p.map(ring))); });

/* Sutherland-Hodgman clip of a ring to the window */
function clip(pts) {
  const edges = [
    [p => p[0] >= W0, (a, b) => [W0, a[1] + (b[1] - a[1]) * (W0 - a[0]) / (b[0] - a[0])]],
    [p => p[0] <= W1, (a, b) => [W1, a[1] + (b[1] - a[1]) * (W1 - a[0]) / (b[0] - a[0])]],
    [p => p[1] >= S0, (a, b) => [a[0] + (b[0] - a[0]) * (S0 - a[1]) / (b[1] - a[1]), S0]],
    [p => p[1] <= N0, (a, b) => [a[0] + (b[0] - a[0]) * (N0 - a[1]) / (b[1] - a[1]), N0]]
  ];
  let out = pts;
  for (const [inside, cut] of edges) {
    const inp = out; out = [];
    for (let i = 0; i < inp.length; i++) {
      const a = inp[i], b = inp[(i + 1) % inp.length], ia = inside(a), ib = inside(b);
      if (ia && ib) out.push(b); else if (ia && !ib) out.push(cut(a, b)); else if (!ia && ib) { out.push(cut(a, b)); out.push(b); }
    }
    if (!out.length) return [];
  }
  return out;
}
const px = ([lon, lat]) => [(lon - W0) * KX, (N0 - lat) * KY];
function dp(pts, eps) {               // Douglas-Peucker
  if (pts.length < 3) return pts;
  const keep = new Array(pts.length).fill(false); keep[0] = keep[pts.length - 1] = true;
  const st = [[0, pts.length - 1]];
  while (st.length) {
    const [a, b] = st.pop(); let md = 0, mi = -1;
    for (let i = a + 1; i < b; i++) {
      const [x, y] = pts[i], [x1, y1] = pts[a], [x2, y2] = pts[b], dx = x2 - x1, dy = y2 - y1, L = dx * dx + dy * dy;
      const d = L ? Math.abs(dy * x - dx * y + x2 * y1 - y2 * x1) / Math.sqrt(L) : Math.hypot(x - x1, y - y1);
      if (d > md) { md = d; mi = i; }
    }
    if (md > eps && mi > 0) { keep[mi] = true; st.push([a, mi], [mi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
let d = '';
for (const p of polys) for (const r of p) {
  const c = clip(r); if (c.length < 3) continue;
  const q = dp(c.map(px), 0.5); if (q.length < 3) continue;
  d += 'M' + q.map(([x, y]) => x.toFixed(1) + ' ' + y.toFixed(1)).join('L') + 'Z';
}
const out = `/* Generated by _dev/punic-map/geo_med.mjs from Natural Earth (public domain). Do not edit by hand. */
const PMAP = { width: ${WIDTH}, height: ${HEIGHT}, w0: ${W0}, n0: ${N0}, kx: ${KX.toFixed(4)}, ky: ${KY}, land: '${d}' };
`;
writeFileSync(join(HERE, '..', '..', 'modules', 'history', 'punic-wars', 'mapdata.js'), out);
console.log('mapdata.js', out.length, 'chars,', WIDTH + 'x' + HEIGHT);
