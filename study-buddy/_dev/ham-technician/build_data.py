"""Builds modules/other/ham-technician/data.js from the official pool (pool.json, parsed from the NCVEC
2026-2030 Technician pool, Feb 19 2026 errata version) and explanations.json (one per question).
Run from the repository root:  python3 -I study-buddy/_dev/ham-technician/build_data.py"""
import json, re, os
here = os.path.dirname(os.path.abspath(__file__))
pool = json.load(open(os.path.join(here, 'pool.json')))
expl = json.load(open(os.path.join(here, 'explanations.json')))
subs = [{'id': k, 'name': v['name'].replace(' And ', ' and '), 'n': v['n']} for k, v in pool['subs'].items()]
def short(t):
    t = re.split(r'[;:]', t)[0].strip()
    return t
groups = [{'id': g, 'sub': g[:2], 'label': short(t), 'topic': t} for g, t in pool['groups'].items()]
qs = []
for q in pool['qs']:
    fig = re.search(r'figure T-(\d)', q['q'], re.I)
    row = {'id': q['id'], 'g': q['id'][:3], 'a': 'ABCD'.index(q['ans']), 'q': q['q'], 'c': q['c'], 'x': expl[q['id']]}
    if q['rule']: row['r'] = q['rule']
    if fig: row['f'] = int(fig.group(1))
    qs.append(row)
assert len(qs) == 409 and all(q['id'] in expl for q in qs)
out = os.path.join(here, '..', '..', 'modules', 'other', 'ham-technician', 'data.js')
js = ('/* Technician exam module: the official 2026-2030 NCVEC Technician (Element 2) question pool, Feb 19 2026 errata version, public domain.\n'
      '   Generated by _dev/ham-technician/build_data.py. SUBS: the 10 subelements (n = questions on the real exam). GROUPS: the 35 topic groups\n'
      '   (the real exam draws one question from each). Q: id, g (group), a (index of the right choice, 0-3), q, c (4 choices, in the official order),\n'
      '   r (FCC rule, if the pool gives one), f (figure number, if the question uses one), x (explanation). */\n'
      'window.HAM = ' + json.dumps({'SUBS': subs, 'GROUPS': groups, 'Q': qs}, ensure_ascii=False, separators=(',', ':')).replace('},{', '},\n{') + ';\n')
open(out, 'w').write(js)
print(len(qs), 'questions,', len(js) // 1024, 'KB')
