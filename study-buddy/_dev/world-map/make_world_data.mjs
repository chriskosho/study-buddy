/* World data: merges the continent modules' data.js files (Europe, Africa, Asia, North America, Oceania) plus South America (from
   _dev/atlas-src/data.js) into modules/geography/world/data.js, so a fact fixed in a continent module is fixed in World when this is re-run.
     node _dev/world-map/make_world_data.mjs
   A country that two continent modules both list (Russia, Turkey, ...) appears once, under the continent in CONT_OF below. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
const HERE = dirname(fileURLToPath(import.meta.url)), ROOT = join(HERE, '..', '..'), GEO = join(ROOT, 'modules', 'geography');
const CONTS = [['europe', 'Europe'], ['asia', 'Asia'], ['africa', 'Africa'], ['north-america', 'North America'], ['south-america', 'South America'], ['oceania', 'Oceania']];
/* the continent for countries that sit on two (the usual atlas choice; the study guide says so in the note) */
const CONT_OF = { ru: 'Europe', tr: 'Asia', kz: 'Asia', ge: 'Asia', am: 'Asia', az: 'Asia', cy: 'Europe', eg: 'Africa' };
/* notes that must differ from the continent module's (Russia's note there says only its western part is on the map) */
const NOTE_OF = { ru: 'Russia is the biggest country in the world. It stretches across Europe and Asia, and most of its people live in the European part.', cy: 'An island country in the Mediterranean Sea. It is close to Asia but is usually grouped with Europe.' };
const ISO2 = { venezuela: 've', colombia: 'co', ecuador: 'ec', peru: 'pe', brazil: 'br', bolivia: 'bo', paraguay: 'py', uruguay: 'uy', argentina: 'ar', chile: 'cl', guyana: 'gy', suriname: 'sr' };
const SA_LANGS = { ve: ['Spanish'], co: ['Spanish'], ec: ['Spanish'], pe: ['Spanish'], br: ['Portuguese'], bo: ['Spanish'], py: ['Spanish', 'Guaraní'], uy: ['Spanish'], ar: ['Spanish'], cl: ['Spanish'], gy: ['English'], sr: ['Dutch'] };
const all = [], also = { name: {}, capital: {}, lang: {} }, flags = {}, seen = new Map();
function run(file, extra = '') { const ctx = {}; vm.createContext(ctx); vm.runInContext(readFileSync(file, 'utf8') + extra, ctx); return ctx; }
for (const [slug, title] of CONTS) {
  if (slug === 'south-america') {
    const c = run(join(ROOT, '_dev/atlas-src/data.js'), '\nthis.R = REGION; this.F = FLAGS; this.E = EXTRA;');
    c.R.countries.forEach(k => {
      const id = ISO2[k.id]; if (!id) throw new Error('no ISO for ' + k.id);
      all.push({ id, name: k.name, capital: k.capital, langs: SA_LANGS[id], cont: title });
      flags[id] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 30 20" role="img" aria-label="Flag of ${k.name}" preserveAspectRatio="xMidYMid slice">${c.F[k.id]()}</svg>`;
    });
    continue;
  }
  const c = run(join(GEO, slug, 'data.js'), '\nthis.C = COUNTRIES; this.A = typeof ALSO === "undefined" ? {} : ALSO; this.F = FLAGS;');
  for (const k of c.C) {
    const want = CONT_OF[k.id] || title;
    if (seen.has(k.id)) { if (want === title) { all[seen.get(k.id)] = { ...k, cont: title }; flags[k.id] = c.F[k.id]; } continue; }
    seen.set(k.id, all.length); all.push({ ...k, cont: want }); flags[k.id] = c.F[k.id];
  }
  for (const f of ['name', 'capital']) Object.entries((c.A[f]) || {}).forEach(([id, v]) => { also[f][id] = [...new Set([...(also[f][id] || []), ...v])]; });
  Object.entries(c.A.lang || {}).forEach(([l, v]) => { also.lang[l] = [...new Set([...(also.lang[l] || []), ...v])]; });
}
all.forEach(k => { if (NOTE_OF[k.id]) k.note = NOTE_OF[k.id]; });
all.sort((a, b) => a.name.localeCompare(b.name));
const miss = all.filter(k => !flags[k.id]).map(k => k.id); if (miss.length) throw new Error('missing flags: ' + miss);
const out = `/* World: content. GENERATED by _dev/world-map/make_world_data.mjs from the continent modules' data.js files (and South America's atlas data),
   so do not edit this file: fix the continent module, then run the script. cont: the continent a country is listed under (a country on two
   continents, such as Russia or Turkey, is listed once). */
const COUNTRIES = ${JSON.stringify(all, null, 0).replace(/\},\{/g, '},\n{').replace(/^\[/, '[\n').replace(/\]$/, '\n]')};
const ALLC = COUNTRIES.slice();                       // every country; COUNTRIES is then narrowed to the picked region by wd-map.js
const ALSO = ${JSON.stringify(also)};
const FLAGS = ${JSON.stringify(flags, null, 0).replace(/","/g, '",\n"')};
`;
mkdirSync(join(GEO, 'world'), { recursive: true });
writeFileSync(join(GEO, 'world', 'data.js'), out);
const by = {}; all.forEach(k => by[k.cont] = (by[k.cont] || 0) + 1);
console.log(all.length, by);
